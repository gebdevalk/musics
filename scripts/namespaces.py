#!/usr/bin/env python3
"""Regenerate doc/md/namespace.md from src/: every namespace, its size in lines and its role.

The role of a namespace is what the table already says (hand-written roles are kept, so edit
them in doc/md/namespace.md), else the first sentence of its docstring or opening comment.
Namespaces nothing in src/ requires are marked unreached (only tests load them).

    python3 scripts/namespaces.py          # rewrites doc/md/namespace.md
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
DOC = ROOT / "doc" / "md" / "namespace.md"

# entry points nothing needs to require
ENTRY = {"musics.mu", "musics.gui.core"}


def ns_name(path):
    rel = path.relative_to(SRC).with_suffix("")
    return ".".join(rel.parts).replace("_", "-")


def first_sentence(text):
    text = re.sub(r"\s+", " ", text).strip()
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    s = s.rstrip(".")
    return (s[:100] + "…") if len(s) > 101 else s


def role_of(path):
    src = path.read_text()
    m = re.search(r'\(ns\s+[^\s)]+\s+"((?:[^"\\]|\\.)*)"', src, re.S)
    if m:
        return first_sentence(m.group(1).replace('\\"', '"'))
    lines = []
    for ln in src.splitlines():
        if ln.startswith(";;"):
            lines.append(ln.lstrip(";").strip())
        elif ln.strip() == "" and not lines:
            continue
        else:
            break
    return first_sentence(" ".join(lines)) if lines else ""


def requires(path):
    src = path.read_text()
    m = re.search(r"\(:require(.*?)\)\s*\)", src, re.S) or re.search(r"\(:require(.*)", src, re.S)
    body = m.group(1) if m else ""
    found = set(re.findall(r"\[\s*(musics\.[\w.\-]+)", body))
    found |= set(re.findall(r"\b(musics\.[\w.\-]+)\b", " ".join(re.findall(r"requiring-resolve\s+'(musics\.[\w.\-]+)", src))))
    found |= set(re.findall(r"requiring-resolve\s+'(musics\.[\w.\-]+)/", src))
    return found


def old_roles():
    """{relative name: role} from the table as it stands."""
    out = {}
    if not DOC.exists():
        return out
    for ln in DOC.read_text().splitlines():
        m = re.match(r"^[│├└─ ]*([A-Za-z][\w.\-*]*)\s+(\d+)\s+(.+?)\s*$", ln)
        if m:
            out[m.group(1)] = re.sub(r"\s*\(unreached\)$", "", m.group(3))
    return out


def pick_role(ns, olds):
    best = None
    for name, role in olds.items():
        if ns == name or ns == "musics." + name or ns.endswith("." + name):
            if best is None or len(name) > len(best[0]):
                best = (name, role)
    return best[1] if best else None


SECTIONS = [
    ("The interfaces", lambda n: n == "musics.mu" or n.startswith("musics.mu.") or n.startswith("musics.gui.")
     or n in {"musics.kernel", "musics.tool", "musics.music", "musics.play", "musics.rate", "musics.soundfont",
              "musics.feedback", "musics.arith", "musics.compare", "musics.version", "musics.assist"}),
    ("Material: text into the store", lambda n: n.startswith("musics.input.") or n.startswith("musics.domain")
     or n in {"musics.repo", "musics.registries", "musics.persist"} or n.startswith("musics.common.")),
    ("Sound: the store into sound", lambda n: n in {"musics.events", "musics.compose", "musics.engine",
                                                    "musics.conductor", "musics.wall"} or n.startswith("musics.midi.")),
    ("Algorithms", lambda n: n.startswith("musics.algo.")),
]


def main():
    files = sorted(SRC.rglob("*.clj"))
    nss = {ns_name(p): p for p in files}
    needed = set()
    for n, p in nss.items():
        needed |= requires(p) - {n}
    olds = old_roles()
    rows = {}
    for n, p in nss.items():
        lines = len(p.read_text().splitlines())
        role = pick_role(n, olds) or role_of(p)
        rows[n] = (lines, role)
    unreached = sorted(n for n in nss if n not in needed and n not in ENTRY and not n.startswith("musics.algo."))
    total = sum(l for l, _ in rows.values())

    out = []
    out.append("# Namespaces\n")
    out.append("Every namespace under `src/`, by section, with its size in lines and its role. The program is "
               "used through **mu** (`musics.mu`, `lein mu`) and the **GUI** (`musics.gui.core`, mu's `gui`). "
               f"{len(nss)} namespaces, {total:,} lines.\n")
    out.append("This page is generated by `python3 scripts/namespaces.py`: sizes and the list come from the "
               "source, and a role you edit here is kept (a new namespace gets the first sentence of its "
               "docstring). *unreached* marks a namespace nothing in `src/` requires, so only tests load it. The algorithms are not marked: a mu user loads one with `reqalgo`.\n")
    width = max(len(n) for n in nss) + 2
    for title, pred in SECTIONS:
        out.append(f"## {title}\n")
        out.append("```")
        group = [n for n in sorted(nss) if pred(n)]
        for n in group:
            lines, role = rows[n]
            mark = " (unreached)" if n in unreached else ""
            out.append(f"{n:<{width}}{lines:>6}   {role}{mark}".rstrip())
        out.append("```\n")
    placed = {n for _, pred in SECTIONS for n in nss if pred(n)}
    left = sorted(set(nss) - placed)
    if left:
        out.append("## Not placed\n")
        out.append("```")
        for n in left:
            lines, role = rows[n]
            out.append(f"{n:<{width}}{lines:>6}   {role}".rstrip())
        out.append("```\n")
    if unreached:
        out.append("## Unreached\n")
        out.append("Required by nothing in `src/`, loaded only by tests (an algorithm is loaded with `reqalgo` and not listed): " + ", ".join(f"`{n}`" for n in unreached) + ".\n")
    DOC.write_text("\n".join(out))
    print(f"wrote {DOC.relative_to(ROOT)}: {len(nss)} namespaces, {total} lines, {len(unreached)} unreached")


if __name__ == "__main__":
    sys.exit(main())
